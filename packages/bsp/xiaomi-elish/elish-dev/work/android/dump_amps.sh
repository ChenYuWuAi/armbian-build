#!/system/bin/sh
# Dump the 27 known audio-relevant CS35L41 registers from all 8 amps (Android)
REGS="0x00000000 0x00000040 0x00002014 0x00002018 0x00002030 0x00002084 0x0000208c 0x0000300c 0x0000394c 0x00004000 0x0000400c 0x0000410c 0x00004160 0x0000416c 0x00004170 0x00004360 0x00004448 0x00004808 0x00004840 0x00006808 0x00006c04 0x00006e30 0x00007068 0x00007418 0x00007434 0x00008004 0x00017040"
for b in 1 2; do
  for a in 0x40 0x41 0x42 0x43; do
    echo "--bus$b-$a--"
    /data/local/tmp/ampreg $b $a dump $REGS
  done
done
